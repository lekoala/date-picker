import { expect, test } from "bun:test";
import {
  createDateAdapter,
  formatLongDate,
  formatMonthYear,
  monthNames,
  monthYearOrder,
  weekdayNames,
} from "../../src/intl.js";

test("date formatters and digit maps reuse locales and distinguish options", () => {
  const originalDate = Intl.DateTimeFormat;
  const originalNumber = Intl.NumberFormat;
  let dates = 0;
  let numbers = 0;
  Intl.DateTimeFormat = new Proxy(originalDate, {
    construct(target, args) {
      dates++;
      return Reflect.construct(target, args);
    },
  });
  Intl.NumberFormat = new Proxy(originalNumber, {
    construct(target, args) {
      numbers++;
      return Reflect.construct(target, args);
    },
  });
  try {
    const locale = "fr-LU-x-cache";
    for (let i = 0; i < 42; i++) expect(formatLongDate("2026-09-06", locale)).toContain("septembre");
    expect(dates).toBe(1);
    expect(formatMonthYear("2026-09", locale)).toContain("septembre");
    monthYearOrder(locale);
    expect(dates).toBe(2);
    expect(formatLongDate("2026-09-06", "en-NZ-x-cache")).toContain("September");
    expect(dates).toBe(3);
    const adapter = createDateAdapter("ar-EG-x-cache");
    for (let i = 0; i < 10; i++) expect(adapter.parse(adapter.format("2026-09-06"))).toBe("2026-09-06");
    expect(numbers).toBe(1);
    expect(() => formatLongDate("2026-09-06", "invalid_locale")).toThrow();
  } finally {
    Intl.DateTimeFormat = originalDate;
    Intl.NumberFormat = originalNumber;
  }
});

test("fr-BE adapter formats and parses the same civil date", () => {
  const adapter = createDateAdapter("fr-BE");
  expect(adapter.placeholder).toBe("DD/MM/YYYY");
  expect(adapter.format("2026-09-06")).toBe("06/09/2026");
  expect(adapter.parse("06/09/2026")).toBe("2026-09-06");
  expect(adapter.parse("2026-09-06")).toBe("2026-09-06");
});

test("en-US adapter uses locale field order", () => {
  const adapter = createDateAdapter("en-US");
  expect(adapter.parse(adapter.format("2026-09-06"))).toBe("2026-09-06");
});

test("adapter round-trips its own formatted output across locales", () => {
  const locales = [
    // Shipped message locales.
    "ar",
    "de",
    "en",
    "es",
    "fr",
    "hi",
    "id",
    "it",
    "ja",
    "ko",
    "nl",
    "pl",
    "pt-BR",
    "pt-PT",
    "ru",
    "tr",
    "zh-CN",
    // Locales whose numeric format embeds spaces or suffixes, plus RTL digits.
    "hu-HU",
    "bg-BG",
    "ko-KR",
    "th-TH",
    "fa-IR",
    "ar-EG",
  ];
  const failures = locales.filter((locale) => {
    const adapter = createDateAdapter(locale);
    const formatted = adapter.format("2026-09-06");
    return adapter.parse(formatted) !== "2026-09-06" || adapter.parse("2026-09-06") !== "2026-09-06";
  });
  expect(failures).toEqual([]);
});

test("locale names are generated by Intl", () => {
  expect(monthNames("fr-BE")).toHaveLength(12);
  expect(weekdayNames("fr-BE", 1)).toHaveLength(7);
});

test("monthYearOrder follows the Intl month/year order", () => {
  expect(monthYearOrder("en-US")).toEqual(["month", "year"]);
  expect(monthYearOrder("fr-BE")).toEqual(["month", "year"]);
  expect(monthYearOrder("ar")).toEqual(["month", "year"]);
  expect(monthYearOrder("ja")).toEqual(["year", "month"]);
  expect(monthYearOrder("zh-CN")).toEqual(["year", "month"]);
});

test("weekdayNames treats 7 as a Sunday alias without shifting 2+", () => {
  expect(weekdayNames("en", 7)).toEqual(weekdayNames("en", 0));
  expect(weekdayNames("en", 7)[0]).toBe("Sun");
  expect(weekdayNames("en", 2)[0]).toBe("Tue");
  expect(weekdayNames("en", 3)[0]).toBe("Wed");
});
